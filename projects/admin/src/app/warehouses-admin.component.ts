import { Component, OnInit, inject, signal } from '@angular/core';
import { FormBuilder, ReactiveFormsModule, Validators } from '@angular/forms';
import { Observable, of, switchMap } from 'rxjs';
import { DataTableComponent, DtColumn } from '@shared/components/data-table.component';
import { ModalComponent } from '@shared/components/modal.component';
import { AdminApiService } from '@shared/core/admin-api.service';
import { AuthService } from '@shared/core/auth.service';
import { I18nService } from '@shared/core/i18n.service';
import { InventoryApiService } from '@shared/core/inventory-api.service';
import { RoleInfo, StaffMember, Warehouse } from '@shared/core/models';
import { TranslatePipe } from '@shared/core/pipes';
import { ToastService } from '@shared/core/toast.service';
import { emptyToNull } from '@shared/core/translation-forms';

// Administrator: the warehouses, and the employees who may work with them (an employee only sees their own warehouses)
@Component({
  selector: 'app-warehouses-admin',
  standalone: true,
  imports: [ReactiveFormsModule, TranslatePipe, DataTableComponent, ModalComponent],
  templateUrl: './warehouses-admin.component.html',
})
export class WarehousesAdminComponent implements OnInit {
  private readonly fb = inject(FormBuilder);
  private readonly api = inject(InventoryApiService);
  private readonly toast = inject(ToastService);
  private readonly i18n = inject(I18nService);
  private readonly adminApi = inject(AdminApiService);
  private readonly auth = inject(AuthService);

  readonly warehouses = signal<Warehouse[]>([]);
  readonly staff = signal<StaffMember[]>([]);
  readonly keeperRoles = signal<RoleInfo[]>([]);
  readonly canManageUsers = (): boolean => this.auth.can('users');
  readonly saving = signal(false);
  readonly wOpen = signal(false);
  readonly wEditing = signal<Warehouse | null>(null);

  readonly wColumns: DtColumn[] = [
    { key: 'name', label: 'a.name', value: (w: Warehouse) => w.name },
    { key: 'code', label: 'inv.code', value: (w: Warehouse) => w.code, width: '90px' },
    { key: 'address', label: 'inv.address', value: (w: Warehouse) => w.address },
    { key: 'keeper', label: 'inv.keeper', value: (w: Warehouse) => this.keepersOf(w) },
    { key: 'items', label: 'inv.items', value: (w: Warehouse) => w.items, type: 'number', width: '80px' },
    { key: 'units', label: 'inv.units', value: (w: Warehouse) => w.units, type: 'number', width: '80px' },
    { key: 'active', label: 'a.active', value: (w: Warehouse) => w.isActive, type: 'bool', width: '90px' },
    { key: 'actions', label: '', width: '170px' },
  ];

  readonly wForm = this.fb.group({
    name: [''],
    nameAr: ['', Validators.required],
    address: [''],
    isActive: [true],
    // The keeper of a NEW warehouse
    keeperMode: ['none'],
    keeperUserId: [''],
    keeperFullName: [''],
    keeperUserName: ['', Validators.pattern(/^([A-Za-z0-9._-]{3,50})?$/)],
    keeperPassword: ['123456'],
    keeperRole: ['WarehouseStaff'],
  });

  ngOnInit(): void {
    this.load();
  }

  load(): void {
    this.api.getWarehouses().subscribe((w) => this.warehouses.set(w));

    if (this.canManageUsers()) {
      this.api.getStaff().subscribe((s) => this.staff.set(s));
      this.adminApi.getRoles().subscribe((r) => this.keeperRoles.set(r.roles.filter((x) => x.name !== 'Admin')));
    }
  }

  // The people in charge of a warehouse (the ones marked "in charge" in their assignment)
  keepersOf(w: Warehouse): string {
    return this.staff().filter((s) => s.managerWarehouseIds?.includes(w.id)).map((s) => s.fullName).join('، ');
  }

  // ---------- warehouses
  editWarehouse(w: Warehouse | null): void {
    this.wEditing.set(w);
    // When no English name was typed, the stored English name is a copy of the Arabic one: show it empty
    this.wForm.reset({ name: w && w.nameEn !== w.nameAr ? w.nameEn : '', nameAr: w?.nameAr ?? w?.nameEn ?? '', address: w?.address ?? '', isActive: w?.isActive ?? true, keeperMode: 'none', keeperUserId: '', keeperFullName: '', keeperUserName: '', keeperPassword: '123456', keeperRole: 'WarehouseStaff' });
    this.wOpen.set(true);
  }

  saveWarehouse(): void {
    if (this.wForm.invalid) {
      this.wForm.markAllAsTouched();
      return;
    }

    const v = this.wForm.getRawValue();
    // The code is generated by the server (WH-001 ...) and kept when editing
    const body = { name: (v.name ?? '').trim(), nameAr: emptyToNull(v.nameAr), code: null, address: emptyToNull(v.address), isActive: !!v.isActive };
    const e = this.wEditing();

    // A new warehouse with a keeper: the keeper's data is checked BEFORE anything is saved
    if (v.keeperMode === 'new' && (!(v.keeperFullName ?? '').trim() || !(v.keeperUserName ?? '').trim() || (v.keeperPassword ?? '').length < 6)) {
      this.wForm.markAllAsTouched();
      this.toast.error(this.i18n.t('inv.keeper.incomplete'));
      return;
    }

    if (v.keeperMode === 'existing' && !v.keeperUserId) {
      this.toast.error(this.i18n.t('inv.keeper.pick'));
      return;
    }

    this.saving.set(true);

    const request: Observable<unknown> = e
      ? this.api.updateWarehouse(e.id, body).pipe(switchMap(() => this.assignKeeper(e.id, v)))
      : this.api.createWarehouse(body).pipe(switchMap((warehouseId) => this.assignKeeper(warehouseId, v)));

    request.subscribe({
      next: () => this.done(this.wOpen),
      error: () => this.saving.set(false),
    });
  }

  // Makes the picked / new employee the keeper (in charge) of the warehouse that was just created
  private assignKeeper(warehouseId: number, v: { keeperMode: string | null; keeperUserId: string | null; keeperFullName: string | null; keeperUserName: string | null; keeperPassword: string | null; keeperRole: string | null }): Observable<unknown> {
    if (v.keeperMode === 'new') {
      return this.api.createStaff({
        userName: (v.keeperUserName ?? '').trim().toLowerCase(),
        fullName: (v.keeperFullName ?? '').trim(),
        password: v.keeperPassword ?? '',
        warehouseIds: [warehouseId],
        managerWarehouseIds: [warehouseId],
        role: v.keeperRole || 'WarehouseStaff',
      });
    }

    const user = v.keeperMode === 'existing' ? this.staff().find((s) => s.id === v.keeperUserId) : undefined;

    if (!user) return of(null);

    return this.api.updateStaff(user.id, {
      fullName: user.fullName,
      isActive: user.isActive,
      role: user.role,
      warehouseIds: [...new Set([...user.warehouseIds, warehouseId])],
      managerWarehouseIds: [...new Set([...(user.managerWarehouseIds ?? []), warehouseId])],
    });
  }

  removeWarehouse(w: Warehouse): void {
    if (!confirm(this.i18n.t('inv.confirmDelete'))) return;
    this.api.deleteWarehouse(w.id).subscribe(() => this.load());
  }

  private done(dialog: { set(v: boolean): void }): void {
    this.saving.set(false);
    dialog.set(false);
    this.toast.success(this.i18n.t('inv.saved'));
    this.load();
  }
}
