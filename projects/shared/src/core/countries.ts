export interface LeafShape {
  continent: string;
  // smooth closed outline
  d: string;
  // midrib + side veins (clip them to the outline)
  veins: string;
}

export function smoothClosed(p: [number, number][], t = 0.55): string {
  const n = p.length;
  let d = `M${p[0][0].toFixed(1)} ${p[0][1].toFixed(1)}`;

  for (let i = 0; i < n; i++) {
    const p0 = p[(i - 1 + n) % n], p1 = p[i], p2 = p[(i + 1) % n], p3 = p[(i + 2) % n];
    const c1 = [p1[0] + ((p2[0] - p0[0]) * t) / 3, p1[1] + ((p2[1] - p0[1]) * t) / 3];
    const c2 = [p2[0] - ((p3[0] - p1[0]) * t) / 3, p2[1] - ((p3[1] - p1[1]) * t) / 3];

    d += ` C${c1[0].toFixed(1)} ${c1[1].toFixed(1)} ${c2[0].toFixed(1)} ${c2[1].toFixed(1)} ${p2[0].toFixed(1)} ${p2[1].toFixed(1)}`;
  }

  return d + ' Z';
}

// Midrib along the long axis of the shape and curved veins sweeping towards the tip
export function leafVeins(pts: [number, number][]): string {
  const n = pts.length;
  const cx = pts.reduce((s, p) => s + p[0], 0) / n;
  const cy = pts.reduce((s, p) => s + p[1], 0) / n;
  let sxx = 0, syy = 0, sxy = 0;

  for (const p of pts) {
    const x = p[0] - cx, y = p[1] - cy;
    sxx += x * x; syy += y * y; sxy += x * y;
  }

  const ang = 0.5 * Math.atan2(2 * sxy, sxx - syy);
  const ux = Math.cos(ang), uy = Math.sin(ang), vx = -uy, vy = ux;
  let lo = Infinity, hi = -Infinity, wl = Infinity, wh = -Infinity;

  for (const p of pts) {
    const a = (p[0] - cx) * ux + (p[1] - cy) * uy;
    const b = (p[0] - cx) * vx + (p[1] - cy) * vy;
    lo = Math.min(lo, a); hi = Math.max(hi, a); wl = Math.min(wl, b); wh = Math.max(wh, b);
  }

  const len = hi - lo, wid = wh - wl, mid = (wl + wh) / 2;
  const P = (a: number, b: number): string => `${(cx + a * ux + b * vx).toFixed(1)} ${(cy + a * uy + b * vy).toFixed(1)}`;
  const parts = [`M${P(lo + len * 0.04, mid)} L${P(hi - len * 0.04, mid)}`];
  const count = len * wid > 2500 ? Math.max(4, Math.min(9, Math.round(len / 16))) : 0;

  for (let i = 1; i <= count; i++) {
    const a = lo + len * (0.12 + (0.8 * i) / (count + 1));
    const reach = wid * 0.75;

    for (const side of [-1, 1]) {
      parts.push(`M${P(a, mid)} Q${P(a + reach * 0.15, mid + side * reach * 0.6)} ${P(a + reach * 0.7, mid + side * reach)}`);
    }
  }

  return parts.join(' ');
}

// Draws the leaves with the map's own projection, so they sit exactly under the pins
export function buildLeaves(project: (lon: number, lat: number) => [number, number]): LeafShape[] {
  return LEAF_DEFS.map(({ continent, pts }) => {
    const px = pts.map(([lon, lat]) => project(lon, lat));

    return { continent, d: smoothClosed(px), veins: leafVeins(px) };
  });
}

function insidePolygon(x: number, y: number, poly: [number, number][]): boolean {
  let inside = false;

  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];

    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }

  return inside;
}

// Which continent a point of the map belongs to (used to light a whole continent up)
export function continentAt(lon: number, lat: number): string {
  if (lon < -169 && lat > 62) return 'AS'; // far east of Russia, across the date line

  for (const d of LEAF_DEFS) if (insidePolygon(lon, lat, d.pts)) return d.continent;

  let best = 'AS';
  let bestDist = Infinity;

  for (const d of LEAF_DEFS) {
    for (const [x, y] of d.pts) {
      const dx = Math.min(Math.abs(x - lon), 360 - Math.abs(x - lon));
      const dist = dx * dx + (y - lat) * (y - lat);

      if (dist < bestDist) {
        bestDist = dist;
        best = d.continent;
      }
    }
  }

  return best;
}

