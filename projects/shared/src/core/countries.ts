export type MarketRole = 'none' | 'export' | 'import' | 'both';

export interface ParsedMarket {
  // country code ("EG") or continent code ("AF")
  code: string;
  kind: 'country' | 'continent';
  role: MarketRole;
}

// The stored value of a market is "EG", "EG|export", "@AF|import" ...  (@ = continent)
export function parseMarket(value: string | null | undefined): ParsedMarket | null {
  const [head, roleRaw] = (value ?? '').trim().split('|');

  if (!head) return null;

  const role: MarketRole = roleRaw === 'export' || roleRaw === 'import' || roleRaw === 'both' ? roleRaw : 'none';

  return head.startsWith('@')
    ? { code: head.slice(1).toUpperCase(), kind: 'continent', role }
    : { code: head.toUpperCase(), kind: 'country', role };
}

export function marketValue(code: string, kind: 'country' | 'continent', role: MarketRole): string {
  const head = kind === 'continent' ? `@${code}` : code;

  return role === 'none' ? head : `${head}|${role}`;
}
