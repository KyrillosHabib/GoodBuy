// A continent outline with its bounding box (used for the leaf veins)
export interface WorldShape {
  continent: string;
  d: string;
  cx: number;
  cy: number;
  w: number;
  h: number;
  // area in px^2: big continents get the full vein pattern, islands only a midrib
  area: number;
}

export const WORLD_SHAPES: WorldShape[] = SHAPES.map(({ continent, pts }) => {
  const xs = pts.map(([lon]) => mapX(lon));
  const ys = pts.map(([, lat]) => mapY(lat));
  const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys);

  return {
    continent,
    d: pts.map(([lon, lat], i) => `${i === 0 ? 'M' : 'L'}${mapX(lon).toFixed(1)} ${mapY(lat).toFixed(1)}`).join(' ') + ' Z',
    cx: (minX + maxX) / 2,
    cy: (minY + maxY) / 2,
    w: maxX - minX,
    h: maxY - minY,
    area: (maxX - minX) * (maxY - minY),
  };
});

